package controller

import (
	"context"
	"fmt"

	v1alpha1 "github.com/instagrim-dev/yas-zeek-operator/api/v1alpha1"
	appsv1 "k8s.io/api/apps/v1"
	corev1 "k8s.io/api/core/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime"
	ctrl "sigs.k8s.io/controller-runtime"
	"sigs.k8s.io/controller-runtime/pkg/client"
	"sigs.k8s.io/controller-runtime/pkg/log"
)

// ZeekReconciler manages only the Zeek engine for a KSensor. Packet transport
// and optional metrics are supplied by the KSensor configuration; they are
// not provisioned by this controller.
type ZeekReconciler struct {
	client.Client
	Scheme *runtime.Scheme
}

func (r *ZeekReconciler) Reconcile(ctx context.Context, req ctrl.Request) (ctrl.Result, error) {
	var sensor v1alpha1.KSensor
	if err := r.Get(ctx, req.NamespacedName, &sensor); err != nil {
		if apierrors.IsNotFound(err) {
			return ctrl.Result{}, nil
		}
		return ctrl.Result{}, err
	}
	if sensor.Spec.Mode == "Legacy" {
		return ctrl.Result{}, nil
	}
	if !sensor.Spec.Engine["NSM"].Enabled {
		return ctrl.Result{}, r.deleteOwnedZeek(ctx, &sensor)
	}
	if sensor.Spec.TenantNamespace != sensor.Namespace {
		return ctrl.Result{}, fmt.Errorf("Zeek tenant namespace %q must equal KSensor namespace %q", sensor.Spec.TenantNamespace, sensor.Namespace)
	}
	engine := &KSensorReconciler{Client: r.Client, Scheme: r.Scheme}
	if err := engine.CreateComponentAppNsmCluster(ctx, log.FromContext(ctx), sensor); err != nil {
		return ctrl.Result{}, err
	}
	return ctrl.Result{}, nil
}

func (r *ZeekReconciler) SetupWithManager(mgr ctrl.Manager) error {
	return ctrl.NewControllerManagedBy(mgr).Named("zeek").For(&v1alpha1.KSensor{}).Owns(&appsv1.StatefulSet{}).Owns(&corev1.Service{}).Owns(&corev1.ConfigMap{}).Complete(r)
}

// deleteOwnedZeek deletes only the fixed resources generated by the Zeek
// renderer and only when this KSensor is their controller. User-managed secrets
// and resources belonging to other sensors or components are left untouched.
func (r *ZeekReconciler) deleteOwnedZeek(ctx context.Context, sensor *v1alpha1.KSensor) error {
	if sensor.UID == "" {
		return nil
	}
	objects := []client.Object{}
	for _, node := range []string{"manager", "proxy", "logger", "worker"} {
		objects = append(objects, &appsv1.StatefulSet{ObjectMeta: metav1.ObjectMeta{Name: "zeek-" + node, Namespace: sensor.Namespace}})
		name := node
		if node != "manager" {
			name += "-001"
		}
		objects = append(objects, &corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: sensor.Namespace}})
	}
	for _, suffix := range []string{"prometheus-server-config", "mesh-config", "cluster-node-cfg", "zeekctl-cfg", "networks-cfg", "local-zeek", "multi-cluster-layout-zeek", "site-scripts"} {
		objects = append(objects, &corev1.ConfigMap{ObjectMeta: metav1.ObjectMeta{Name: "nsm-" + suffix, Namespace: sensor.Namespace}})
	}
	for _, obj := range objects {
		if err := r.Get(ctx, client.ObjectKeyFromObject(obj), obj); err != nil {
			if apierrors.IsNotFound(err) {
				continue
			}
			return err
		}
		if !metav1.IsControlledBy(obj, sensor) {
			continue
		}
		uid, version := obj.GetUID(), obj.GetResourceVersion()
		if err := r.Delete(ctx, obj, client.Preconditions{UID: &uid, ResourceVersion: &version}); err != nil && !apierrors.IsNotFound(err) {
			return err
		}
	}
	return nil
}
